#!/bin/sh -e
#
# Sets up Alpine Linux dependencies required to prepare an Archlinux ARM
# installation.
#
################################################################################

set -o pipefail

################################################################################

echo "-------------------------------------------------------------------------"
echo "- Checking environment...                                               -"
echo "-------------------------------------------------------------------------"

hash apk

################################################################################

echo "-------------------------------------------------------------------------"
echo "- Installing dependencies...                                            -"
echo "-------------------------------------------------------------------------"

apk add --no-cache     \
  arch-install-scripts \
  bash                 \
  btrfs-progs          \
  dosfstools           \
  e2fsprogs            \
  e2fsprogs-extra      \
  findmnt              \
  sgdisk

###############################################################################

echo "-------------------------------------------------------------------------"
echo "- DONE!                                                                 -"
echo "-------------------------------------------------------------------------"

################################################################################
